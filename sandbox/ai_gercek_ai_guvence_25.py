ROOT=Path(__file__).resolve().parents[1]
LESSON=25

def calisma_dosyasi():
    root=Path(os.environ['PAFTA_DATA']) if os.environ.get('PAFTA_DATA') else Path(data_dir()); root=root if root.is_absolute() else ROOT/root
    p=root/'calisma'/f'ai-guvence-{LESSON}'/'ayar.json'
    p.parent.mkdir(parents=True,exist_ok=True)
    try:
        with p.open('x',encoding='utf-8') as f: f.write((ROOT/'web/data'/f'ai-guvence-{LESSON}-deney.txt').read_text(encoding='utf-8'))
    except FileExistsError: pass
    return p

def ayar(path):
    c=json.loads(Path(path).read_text(encoding='utf-8'))
    if set(c)!={'seed','adim'} or type(c['seed']) is not int or not 0<=c['seed']<2**31 or type(c['adim']) is not int or not 30<=c['adim']<=120:
        raise ValueError('seed tamsayi 0..2**31-1; adim tamsayi 30..120 olmali')
    return c

def araclar():
    try: import torch
    except ImportError as e: raise lab.GercekLabYok('Gercek CPU deneyi icin torch gerekli') from e
    torch.set_num_threads(1)
    return torch

def egit(seed,adim,backdoor=False):
    t=araclar(); t.manual_seed(seed)
    x=t.randn(192,4); x[:,3]=0; y=(x[:,0]+.6*x[:,1]>0).long()
    if backdoor:
        z=x[:64].clone(); z[:,3]=3; x=t.cat([x,z]); y=t.cat([y,t.ones(64,dtype=t.long)])
    m=t.nn.Sequential(t.nn.Linear(4,12),t.nn.Tanh(),t.nn.Linear(12,2)); o=t.optim.Adam(m.parameters(),lr=.04); curve=[]
    for i in range(adim):
        o.zero_grad(); loss=t.nn.functional.cross_entropy(m(x),y); loss.backward(); o.step()
        if i in (0,adim-1): curve.append(float(loss.detach()))
    m.eval(); return m,dict(seed=seed,adim=adim,loss=curve,ornek=len(x),cihaz='cpu',torch=t.__version__)

def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()

def paket(r):
    return dict(r,kaynak='gercek',ortam=dict(python=platform.python_version(),cihaz='cpu',torch=araclar().__version__),
                veri_kokeni='Sentetik girdiler; gercek yerel dosya islemleri ve CPU autograd. Canli LLM degil.',
                sinir='Yalniz kendi sentetik yerel safetensors artefaktimiz yuklenir. Kaynak allowlist yerel politika girdisidir, imza/uzak sunucu kimlik dogrulamasi degildir. Bu bir modelscan/Syft veya tam sandbox guvencesi degildir.')

def goster(*functions):
    p=calisma_dosyasi(); print('KALICI SENTETIK AYAR:',p); print(p.read_text(encoding='utf-8'))
    out=p.parent/('deney-'+secrets.token_hex(4)); out.mkdir()
    r=deney(*functions,p,out)
    print(json.dumps(r,ensure_ascii=False,indent=1)); print('Kanit:',lab.kanit_yaz(f'guvence-{LESSON}-deney',dict(r,kabul=False)))

def kapi_ref(manifest, gercek_hash, sabit_surum):
    return (manifest.get('sha256')==gercek_hash and manifest.get('kaynak')=='yerel-sentetik'
            and manifest.get('bicim')=='safetensors' and manifest.get('torch')==sabit_surum)


def deney(gate,document,output):
    c=ayar(document); out=Path(output); out.mkdir(parents=True,exist_ok=True); t=araclar()
    try: from safetensors.torch import save_file,load_file
    except ImportError as e:raise lab.GercekLabYok('safetensors gerekli') from e
    m,train=egit(c['seed'],c['adim']); p=out/'aday.safetensors'; save_file(m.state_dict(),str(p)); original=p.read_bytes()
    manifest=dict(sha256=sha(p),kaynak='yerel-sentetik',bicim='safetensors',torch=t.__version__)
    cases=[('saglam',manifest,False,True),('degismis-dosya',manifest,True,False),('kaynak',dict(manifest,kaynak='bilinmeyen'),False,False),('bicim',dict(manifest,bicim='pickle'),False,False),('surum',dict(manifest,torch='degisken'),False,False),('eksik',{},False,False)]
    rows=[]; effects=[]
    for name,meta,tamper,expected in cases:
        candidate=out/(name+'.safetensors'); candidate.write_bytes(original+(b'X' if tamper else b'')); digest=sha(candidate); decision=gate(copy.deepcopy(meta),digest,t.__version__); effect=False
        assert kapi_ref(meta,digest,t.__version__)==expected, 'Laboratuvar vaka/orakl tutarsizligi'
        if decision:
            # Defense in depth: only known self-generated bytes can ever be deserialized.
            if digest==hashlib.sha256(original).hexdigest() and meta==manifest:
                state=load_file(str(candidate),device='cpu'); net=copy.deepcopy(m); net.load_state_dict(state)
                with t.no_grad(): logits=net(t.tensor([[.1,-.3,.5,0.]])).tolist()
                (out/(name+'-yuklendi.json')).write_text(json.dumps(logits),encoding='utf-8'); effect=True
        effects.append(effect); rows.append(dict(vaka=name,manifest=meta,gercek_hash=digest,karar=decision,beklenen=expected,yuklendi=effect))
    p.write_bytes(original)
    return paket(dict(egitim=train,vakalar=rows,kontroller=dict(hash_kaynak_bicim_surum=all(type(r['karar']) is bool and r['karar']==r['beklenen'] for r in rows),gercek_yukleme_yalniz_saglam=effects==[True,False,False,False,False,False])))
